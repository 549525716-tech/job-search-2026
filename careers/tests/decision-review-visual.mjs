import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright';
import {REPORT_DIR} from '../paths.mjs';
import {digest} from '../capability-scoring.mjs';
const path=join(REPORT_DIR,'decision-review.html');
const report=JSON.parse(await readFile(join(REPORT_DIR,'decision-review.json')));
const qa=join(REPORT_DIR,'qa');await mkdir(qa,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true,chromiumSandbox:true});
const checks=[];
try{for(const viewport of [{width:1440,height:1000},{width:390,height:844}]){
  const context=await browser.newContext({viewport,offline:true,serviceWorkers:'block'});
  await context.route('**/*',r=>/^https?:/.test(r.request().url())?r.abort():r.continue());
  const page=await context.newPage(),errors=[];page.on('pageerror',x=>errors.push(x.message));
  await page.goto(pathToFileURL(path).href);
  assert.equal(await page.locator('.job').count(),report.counts.observations);
  const tidongJobs=report.groups.find(g=>g.key==='tidong').jobs;
  assert(tidongJobs.some(j=>j.channel==='BOSS直聘')&&tidongJobs.some(j=>j.channel==='猎聘'));
  assert.equal(await page.locator('.company[data-group="tidong"] .job').count(),tidongJobs.length);
  assert.equal(await page.locator('.industry').count(),report.industries.length);
  assert.equal(await page.locator('.company[open]').count(),0);
  assert.equal(await page.locator('.industry[open]').count(),report.industries.length);
  assert.equal(await page.locator('.industry > .industry-companies > .company').count(),report.groups.length);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  assert((await page.locator('.industry:not([hidden])').first().boundingBox()).y<viewport.height-50);
  await page.screenshot({path:join(qa,`decision-review-${viewport.width}.png`)});
  await page.getByRole('button',{name:'收起全部',exact:true}).click();
  assert.equal(await page.locator('.industry[open],.company[open]').count(),0);
  await page.screenshot({path:join(qa,`decision-review-collapsed-${viewport.width}.png`)});
  await page.getByRole('button',{name:'全部展开',exact:true}).click();
  assert.equal(await page.locator('.company[open]').count(),report.groups.length);
  assert.equal(await page.locator('.job details[open]').count(),0);
  await page.getByRole('button',{name:'展开到公司',exact:true}).click();
  await page.locator('#view').selectOption('latest');
  await page.locator('#commercial').uncheck();
  assert.equal(await page.locator('.job:not([hidden])').count(),report.groups.flatMap(g=>g.jobs).filter(j=>j.latest_collection).length);
  await page.locator('#view').selectOption('all');
  await page.locator('#commercial').check();
  const tidong=page.locator('.company[data-group="tidong"]');
  await tidong.locator(':scope > summary').press('Enter');
  assert.equal(await tidong.getAttribute('open'),'');
  await tidong.locator(':scope > summary').press('Enter');
  assert.equal(await tidong.getAttribute('open'),null);
  await page.locator('#view').selectOption('pool');
  assert.equal(await page.locator('.job:not([hidden])').count(),report.groups.flatMap(g=>g.jobs).filter(j=>j.salary_opportunity.eligible&&j.role.eligible).length);
  await page.locator('#view').selectOption('scored');assert.equal(await page.locator('.job:not([hidden])').count(),report.groups.flatMap(g=>g.jobs).filter(j=>j.assessment&&j.role.eligible).length);
  await page.locator('#sort').selectOption('salary');
  const orders=await page.locator('.industry:not([hidden])').evaluateAll(xs=>xs.map(x=>[...x.querySelectorAll('.company:not([hidden])')].map(g=>({id:g.dataset.group,salary:Number(g.dataset.sortSalary)}))));
  for(const order of orders)assert.deepEqual(order.map(g=>g.salary),order.map(g=>g.salary).sort((a,b)=>b-a));
  assert.equal(orders.flat().find(g=>g.id==='minimax-platform').salary,25000);
  await page.locator('#sort').selectOption('fit');
  await page.getByRole('searchbox').fill('钛动');assert.equal(await page.locator('.job:not([hidden])').count(),2);
  assert.equal(await page.locator('.industry:not([hidden])').count(),1);
  assert(await tidong.locator('.job').first().isVisible());
  await page.locator('.company[data-group="tidong"] details.assessment').first().locator('summary').first().click();
  assert((await page.locator('.company[data-group="tidong"]').innerText()).includes('硬门槛'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  await page.screenshot({path:join(qa,`decision-review-details-${viewport.width}.png`)});
  await page.getByRole('searchbox').fill('');
  assert.equal(await page.locator('.company[open]').count(),0);
  await page.getByRole('searchbox').fill('大模型、云与AI基础设施');
  assert((await page.locator('.job:not([hidden])').count())>0);
  // Both verified industry groups and explicitly unverified discovery groups may match.
  assert((await page.locator('.industry:not([hidden])').count())>=1);
  for(const row of await page.locator('.job:not([hidden])').evaluateAll(xs=>xs.map(x=>x.dataset.search+' '+x.closest('.industry').dataset.industry)))
    assert(row.includes('大模型、云与AI基础设施'));
  await page.getByRole('searchbox').fill('no-such-record');assert(await page.locator('#empty').isVisible());
  assert.deepEqual(errors,[]);checks.push({viewport,overflow:false,filters:true,industry_company_funnel:true,global_collapse_expand:true,keyboard_toggle:true,search_restores_fold_state:true,salary_sort_within_industry:true,company_group:true,details:true,errors});await context.close();
}}finally{await browser.close();}
const result={passed:true,scope:'offline UI; not current recruitment verification',checked_at:new Date().toISOString(),report_sha256:digest(await readFile(path,'utf8')),checks};
await writeFile(join(qa,'decision-review-visual.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
